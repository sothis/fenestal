/* ---- palette ------------------------------------------------------------ */

/* Authored in sRGB and indexed by OverlayColor in app.h, which says what each
 * is for. */
static const float PALETTE[][4] = {
	[COL_BAR_ON]   = { 0.16f, 0.16f, 0.18f, 1.0f },
	[COL_BAR_OFF]  = { 0.12f, 0.12f, 0.13f, 1.0f },
	[COL_LINE_ON]  = { 0.30f, 0.30f, 0.34f, 1.0f },
	[COL_LINE_OFF] = { 0.21f, 0.21f, 0.24f, 1.0f },
	[COL_ICON_ON]  = { 0.92f, 0.92f, 0.92f, 1.0f },
	[COL_ICON_OFF] = { 0.55f, 0.55f, 0.58f, 1.0f },
	[COL_CLOSE]    = { 0.78f, 0.16f, 0.16f, 1.0f },
	/* The titlebar controls. */
	[COL_CTL_BOX]    = { 0.12f, 0.12f, 0.14f, 1.0f },
	[COL_CTL_DIM]    = { 0.45f, 0.48f, 0.55f, 1.0f },
	[COL_CTL_LIVE]   = { 0.35f, 1.00f, 0.55f, 1.0f },
	[COL_CTL_HILITE] = { 0.20f, 0.32f, 0.24f, 1.0f },
	/* The metrics panel's, beside the controls' box, line, live and dim:
	 * the slower half of a frame red, as the faster is COL_CTL_LIVE's
	 * green, and the rate the slower allows yellow. */
	[COL_MET_HEAD]   = { 1.00f, 0.78f, 0.30f, 1.0f },
	[COL_MET_SLOW]   = { 1.00f, 0.38f, 0.35f, 1.0f },
	[COL_MET_RATE]   = { 1.00f, 0.92f, 0.25f, 1.0f },
};

_Static_assert(sizeof PALETTE / sizeof PALETTE[0] == COL_COUNT,
			   "PALETTE and OverlayColor disagree -- a designated initialiser "
			   "that names no entry past the last one leaves the array short");

/* Once per device, as soon as the surface format is known. Alpha is linear in
 * both encodings; see the palette note in app.h for the rest. */
void app_palette_init(App *a)
{
	for (int i = 0; i < COL_COUNT; i++) {
		for (int c = 0; c < 3; c++)
			a->pal[i][c] = a->srgb_surface ? srgb_to_linear(PALETTE[i][c])
										   : PALETTE[i][c];
		a->pal[i][3] = PALETTE[i][3];
	}
}

/* From the authored table and not App::pal, which is linear on an sRGB
 * surface and is the render thread's. */
void app_bar_srgb8(bool active, uint8_t rgb[3])
{
	const float *c = PALETTE[active ? COL_BAR_ON : COL_BAR_OFF];
	for (int i = 0; i < 3; i++)
		rgb[i] = (uint8_t)(c[i] * 255.0f + 0.5f);
}

/* ---- appending ---------------------------------------------------------- */

/* Coverage ramp half-width, in physical pixels: wide enough to hide the
 * staircase, narrow enough that strokes still read as crisp. */
#define STROKE_FEATHER_PX 0.5f

/* Window-space point -> buffer pixel without the rounding surf_pt() does, for
 * geometry whose subpixel position matters: the antialiased strokes. */
static float surf_ptf(const App *a, float v, int s120)
{
	return (v + (float)a->draw_margin) * (float)s120 / 120.0f;
}

void overlay_begin(App *a, uint32_t img)
{
	a->ovl_img      = img;
	a->rect_count   = a->rect_drawn  = 0;
	a->shape_count  = a->shape_drawn = 0;
	a->overlay_open = true;
	/* Nothing is narrowed at the top of a recording: the command buffer's
	 * scissor was set to the whole framebuffer when the pass began. */
	a->overlay_clipped = false;
}

/* Called once the frame's three draws have been issued: an append arriving
 * afterwards is refused rather than landing in the arena of an image whose
 * command buffer is still executing. See App::overlay_open. */
void overlay_end(App *a)
{
	a->overlay_open = false;
}

bool overlay_clip(const App *a, int x, int y, int w, int h, FnlRect *out)
{
	const int s120 = scale120(a);
	int x0 = surf_pt(a, x, s120),     y0 = surf_pt(a, y, s120);
	int x1 = surf_pt(a, x + w, s120), y1 = surf_pt(a, y + h, s120);
	const int mw = (int)a->extent.w, mh = (int)a->extent.h;

	if (x0 < 0)  x0 = 0;
	if (y0 < 0)  y0 = 0;
	if (x1 > mw) x1 = mw;
	if (y1 > mh) y1 = mh;
	if (x1 <= x0 || y1 <= y0)
		return false;

	out->x = x0;
	out->y = y0;
	out->w = x1 - x0;
	out->h = y1 - y0;
	return true;
}

void overlay_rect(App *a, int x, int y, int w, int h, const float color[4])
{
	FnlRect r;
	if (!a->overlay_open || a->rect_count >= OVERLAY_MAX_RECTS ||
		!a->ovl_map[a->ovl_img] || !overlay_clip(a, x, y, w, h, &r))
		return;

	RectInstance *o = (RectInstance *)a->ovl_map[a->ovl_img] + a->rect_count++;
	o->rect[0] = (float)r.x;
	o->rect[1] = (float)r.y;
	o->rect[2] = (float)r.w;
	o->rect[3] = (float)r.h;
	memcpy(o->color, color, sizeof o->color);
}

/* A one-point outline just inside a rectangle. Top, bottom, left, right. */
void overlay_frame(App *a, int x, int y, int w, int h, const float color[4])
{
	overlay_rect(a, x, y, w, 1, color);
	overlay_rect(a, x, y + h - 1, w, 1, color);
	overlay_rect(a, x, y, 1, h, color);
	overlay_rect(a, x + w - 1, y, 1, h, color);
}

void overlay_elbow(App *a, float x0, float y0, float x1, float y1,
				   float x2, float y2, float width, const float color[4])
{
	if (!a->overlay_open || a->shape_count >= OVERLAY_MAX_SHAPES ||
		!a->ovl_map[a->ovl_img])
		return;

	const int s120 = scale120(a);
	ShapeInstance *o = (ShapeInstance *)(a->ovl_map[a->ovl_img] +
										 OVERLAY_SHAPE_OFF) + a->shape_count++;
	o->p0[0] = surf_ptf(a, x0, s120); o->p0[1] = surf_ptf(a, y0, s120);
	o->p1[0] = surf_ptf(a, x1, s120); o->p1[1] = surf_ptf(a, y1, s120);
	o->p2[0] = surf_ptf(a, x2, s120); o->p2[1] = surf_ptf(a, y2, s120);
	o->half_w  = width * (float)s120 / 120.0f * 0.5f;
	o->feather = STROKE_FEATHER_PX;
	memcpy(o->color, color, sizeof o->color);
}

void overlay_stroke(App *a, float x0, float y0, float x1, float y1,
					float width, const float color[4])
{
	/* A degenerate second segment: the shader takes the nearer of the two, and
	 * a point that already lies inside the first capsule never wins. */
	overlay_elbow(a, x0, y0, x1, y1, x1, y1, width, color);
}

void overlay_box(App *a, float x0, float y0, float x1, float y1,
				 float width, const float color[4])
{
	/* A second arm folded back onto the first is what an elbow can never be,
	 * so the shader reads it as opposite corners of a rectangle. Packed
	 * through overlay_elbow() so that one function writes ShapeInstance. */
	overlay_elbow(a, x0, y0, x1, y1, x0, y0, width, color);
}

void text_begin(App *a, uint32_t img)
{
	/* create_swapchain() refuses an image count above OVERLAY_MAX_IMAGES, so
	 * the index is the image's own rather than a wrapped one -- wrapping would
	 * put two in-flight frames on one buffer. */
	a->text_img = img;
	a->text_count = 0;
	a->text_drawn = 0;
}

/* Append one string, UTF-8; text_end() draws it.
 *
 * Both the pen and every glyph land on whole physical pixels: the atlas holds
 * coverage computed for this pixel grid, and a quad at a fractional offset
 * would resample it. The pen is rounded per glyph rather than stepped by a
 * fixed pixel advance, which keeps the string's length honest at fractional
 * scales. */
void text_draw(App *a, int x, int y, TextSize sz, const float color[4],
			   const char *s)
{
	if (!a->overlay_open)
		return;
	GlyphInstance *out = a->text_map[a->text_img];
	if (!out || a->font_si < 0)
		return;

	const int  s120 = scale120(a);
	const int  adv  = text_advance(sz);
	const bool mono = text_is_mono(sz);
	/* The proportional pen starts here and walks; see below. */
	const int  origin_px = surf_pt(a, x, s120);

	/* Exactly 1.0 inside the baked range, so nothing about the common path
	 * moves; past either end, what text_resampled() explains. */
	const float qf = text_resampled(a)
						 ? (float)s120 / (float)FONT_SCALE[a->font_si]
						 : 1.0f;
	/* `y` is the top of the glyph box; the baseline is one cap height below,
	 * which is what the overlay's vertical centring is written against. */
	const int base_px = surf_pt(a, y + text_height(sz), s120);

	/* NULL when text_load_cells() has not run, and cell_for() indexes the row
	 * it is handed: one test per string instead of a null read per glyph. */
	const GlyphCell *row = cell_row(a->font_si, sz);
	if (!row)
		return;
	const float inv_aw = 1.0f / (float)a->font_atlas_w;
	const float inv_ah = 1.0f / (float)a->font_atlas_h;

	/* Where the pen is, for a proportional size: pixels accumulated from the
	 * start of the string, because there is no per-size step to multiply an
	 * index by. Monospaced sizes ignore it and keep the arithmetic below. */
	float pen_prop = 0.0f;

	/* How far the walk may go, as a division on a known-good bound rather than
	 * a multiplication left to wrap. The pen is `x + i * adv`, and a glyph
	 * with no ink appends nothing, so the TEXT_MAX_GLYPHS break below never
	 * trips on a run of spaces. OVERLAY_COORD_MAX is the bound the
	 * coordinates are clamped to (see clamp_pt in app.h); the proportional
	 * face has no step to divide by and takes it as a count. */
	const int max_i = adv > 0 ? (OVERLAY_COORD_MAX - x) / adv
							  : OVERLAY_COORD_MAX;

	for (int i = 0; *s; i++) {
		if (i > max_i)
			break;

		uint32_t cp;
		s = utf8_next(s, &cp);

		const GlyphCell *cl = cell_for(row, cp);
		if (!cl)
			continue;
		/* Do not hoist the monospaced pen to a start and a step: that is
		 * algebraically equal and not the same answer, straddling a rounding
		 * tie about once in ten thousand positions.
		 *
		 * Monospaced: the point position, rounded once per glyph.
		 * Proportional: the advances are pixels at this scale, so the
		 * string's origin is rounded once and the steps accumulate. */
		int pen_px = mono ? surf_pt(a, x + i * adv, s120)
						  : origin_px + (int)(pen_prop + 0.5f);
		/* Stepped before the glyph is drawn rather than after: a glyph with no
		 * ink still moves the pen, and the width measure counts it. */
		pen_prop += (float)cl->adv * qf;

		if (!cl->w || !cl->h)
			continue;                             /* space, or a blank glyph */
		if (a->text_count >= TEXT_MAX_GLYPHS)
			break;

		GlyphInstance *o = &out[a->text_count++];
		/* The offsets scale with the box: they are the bitmap's placement
		 * relative to the pen, in the grid it was baked for. The pen itself
		 * does not -- it was computed at the true scale to begin with. */
		o->rect[0] = (float)pen_px + (float)cl->left * qf;
		o->rect[1] = (float)base_px + (float)cl->top * qf;
		o->rect[2] = (float)cl->w * qf;
		o->rect[3] = (float)cl->h * qf;
		/* Three texels to the pixel across, one row to the pixel down. Spanning
		 * the cell's full texel width means the interpolated coordinate lands
		 * on the middle of each pixel's three -- the green emitter -- and the
		 * fragment shader steps one texel either side for red and blue. */
		o->uv[0] = (float)cl->x * inv_aw;
		o->uv[1] = (float)cl->y * inv_ah;
		o->uv[2] = (float)(cl->x + 3 * cl->w) * inv_aw;
		o->uv[3] = (float)(cl->y + cl->h) * inv_ah;
		/* Already in the surface's blend space: app_palette_init() converted
		 * the whole palette once, when the format was resolved. */
		memcpy(o->color, color, sizeof o->color);
	}
}

/* The draws themselves are the running renderer's. */
